# ========== 巩固打分权重 ==========
# 睡觉时给每条短期记忆算一个巩固分（promote_score），就是四个分数加权求和。
# 哪个维度更看重，就把它的权重调大。
SCORE_WEIGHTS = {
    "emotional_impact": 0.35,   # 情感冲击
    "motivation_match": 0.25,   # 动机吻合
    "interest_score": 0.20,     # 兴趣指数
    "anomaly": 0.10,            # 反常程度
    "repeat": 0.10,             # 重复次数，出现越多次越值得记
}

# 巩固分的存入线：过线的存进长期记忆库，不过线的忘掉
SAVE_SCORE = 50

# 余弦相似度超过这个值，就当作同一条记忆（范围 0~1，调大了判重更严格）
SIMILARITY_THRESHOLD = 0.85

# 回忆的时候取几条旧记忆
TOP_K = 5
